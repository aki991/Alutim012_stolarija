import { expect, test } from '@playwright/test';

const job='/posao/AT-2026-012';

test('Bira Porta Royal dekor i tip, čuva terenske mere i izvozi specifikaciju',async({page},testInfo)=>{
 await page.setViewportSize({width:390,height:844});
 await page.route('https://portaroyal.rs/wp-content/uploads/**',route=>route.abort());
 await page.goto(`${job}/dodaj`);
 await page.getByRole('link',{name:'Sobna vrata',exact:true}).click();
 await expect(page.getByRole('status').filter({hasText:'814 varijanti'})).toBeVisible();
 await expect(page.locator('.porta-series-card')).toHaveCount(15);
 await page.getByLabel('Kolekcija',{exact:true}).selectOption('eko-furnir-lux');
 await expect(page.locator('.porta-series-card')).toHaveCount(4);
 await page.getByRole('button',{name:/Eko Furnir Lux Classic/}).click();
 await expect(page).toHaveURL(/\/nov\/sobna-vrata\?serija=eko-furnir-lux-classic/);
 await expect(page.getByLabel('Širina (mm)',{exact:true})).toBeInViewport();
 await expect(page.getByLabel('Debljina zida (mm)',{exact:true})).toBeVisible();
 await expect(page.getByLabel('Ispuna',{exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Nastavi',exact:true})).toHaveCount(0);
 await page.getByLabel('Dekor',{exact:true}).selectOption('nordijski-hrast');
 await page.getByRole('button',{name:'Tip K',exact:true}).click();
 await expect(page.getByRole('img',{name:'Skica tipa K'})).toBeVisible();
 await expect(page.getByLabel('Dekor',{exact:true})).toHaveValue('nordijski-hrast');
 await expect(page.getByLabel('Tip vrata',{exact:true})).toHaveValue('k');
 await expect(page.getByRole('group',{name:'Širina vrata',exact:true})).toHaveText('890 mm');
 await expect(page.getByRole('group',{name:'Visina vrata',exact:true})).toHaveText('2060 mm');
 await page.getByRole('button',{name:'Povećaj širinu',exact:true}).click();
 await page.getByRole('button',{name:'Povećaj visinu',exact:true}).click();
 await expect(page.getByRole('group',{name:'Širina vrata',exact:true})).toHaveText('900 mm');
 await expect(page.getByRole('group',{name:'Visina vrata',exact:true})).toHaveText('2070 mm');
 await page.reload();
 await expect(page.getByLabel('Širina (mm)',{exact:true})).toHaveValue('900');
 await expect(page.getByRole('button',{name:'Dodaj u posao',exact:true})).toBeEnabled();
 await expect(page.getByLabel('Širina (mm)',{exact:true})).toHaveValue('900');
 await expect(page.getByLabel('Visina (mm)',{exact:true})).toHaveValue('2070');
 await expect(page.locator('.porta-editor-preview .field-drawing')).toHaveCount(0);
 const door=page.locator('.porta-editor-preview .porta-photo-door');
 const photoSize=()=>door.evaluate(el=>({width:el.clientWidth,height:el.clientHeight}));
 const starting=await photoSize();
 await page.getByLabel('Širina (mm)',{exact:true}).fill('920');
 const wider=await photoSize();
 expect(wider.width).toBeGreaterThan(starting.width);
 expect(Math.abs(wider.height-starting.height)).toBeLessThanOrEqual(1);
 await page.getByLabel('Visina (mm)',{exact:true}).fill('2090');
 expect((await photoSize()).height).toBeGreaterThan(wider.height);
 await expect(page.getByRole('group',{name:'Širina vrata',exact:true})).toHaveText('920 mm');
 await expect(page.getByRole('group',{name:'Visina vrata',exact:true})).toHaveText('2090 mm');
 expect(await page.evaluate(()=>document.querySelector('.porta-editor-preview')!.getBoundingClientRect().bottom<=document.querySelector('.porta-editor-fields')!.getBoundingClientRect().top)).toBe(true);
 await page.getByLabel('Debljina zida (mm)',{exact:true}).fill('170');
 await page.getByLabel('Smer klizanja',{exact:true}).selectOption('right');
 await page.getByLabel('Ispuna',{exact:true}).selectOption('chipboard');
 await page.getByLabel('Dodatni otvor',{exact:true}).selectOption('O2');
 await page.reload();
 await expect(page.getByLabel('Smer klizanja',{exact:true})).toHaveValue('right');
 await expect(page.getByLabel('Ispuna',{exact:true})).toHaveValue('chipboard');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByRole('button',{name:'Dodaj u posao',exact:true}).click();
 await expect(page.locator('.job-line').last()).toContainText('Eko Furnir Lux Classic · Nordijski hrast · K');
 await expect(page.locator('.job-line').last()).toContainText('Cena po upitu');
 await page.getByRole('link',{name:'Izmeni element 4',exact:true}).click();
 await expect(page.getByLabel('Debljina zida (mm)',{exact:true})).toHaveValue('170');
 await expect(page.getByLabel('Dodatni otvor',{exact:true})).toHaveValue('O2');
 await page.getByRole('button',{name:'Sačuvaj izmene',exact:true}).click();
 await page.getByRole('link',{name:/Podeli dokument/i}).click();
 await expect(page.locator('.price-line').last()).toContainText('Tip K · Nordijski hrast');
 await page.getByRole('button',{name:'Specifikacija za kancelariju',exact:true}).click();
 const download=page.waitForEvent('download');
 await page.getByRole('button',{name:'Preuzmi PDF',exact:true}).click();
 await (await download).saveAs(testInfo.outputPath('porta-royal-specifikacija.pdf'));
});

test('Poseban katalog može da započne nov posao sa izabranom serijom i cenom iz cenovnika',async({page})=>{
 await page.route('https://portaroyal.rs/wp-content/uploads/**',route=>route.abort());
 await page.goto('/cenovnik');
 await page.getByText('Sobna vrata Porta Royal',{exact:true}).click();
 await page.getByLabel('CPL Bela Premium (€/kom.)',{exact:true}).fill('240');
 await page.goto('/katalog');
 await page.getByRole('link',{name:'Sobna vrata',exact:true}).click();
 await page.getByRole('searchbox',{name:'Pretraži sobna vrata'}).fill('cpl bela premium');
 await expect(page.locator('.porta-series-card')).toHaveCount(1);
 await page.locator('.porta-series-card').click();
 await expect(page.getByRole('dialog',{name:'Novi posao'})).toHaveCount(0);
 await expect(page.getByLabel('Debljina zida (mm)',{exact:true})).toBeVisible();
 await expect(page.getByLabel('Tip vrata',{exact:true}).locator('option')).toHaveCount(11);
 await page.getByRole('button',{name:'Tip DK',exact:true}).click();
 await expect(page.getByLabel('Širina (mm)',{exact:true})).toHaveValue('1450');
 await page.getByLabel('Širina (mm)',{exact:true}).fill('1800');
 await page.getByLabel('Visina (mm)',{exact:true}).fill('2110');
 await page.reload();
 await expect(page.getByLabel('Širina (mm)',{exact:true})).toHaveValue('1800');
 await expect(page.locator('.measurement-amount strong')).toContainText('240,00');
 await expect(page.getByLabel('Ispuna',{exact:true})).toHaveValue('solid');
 await page.getByRole('button',{name:'Dodaj u posao',exact:true}).click();
 await page.getByLabel('Naziv posla ili prezime kupca').fill('Sobna vrata test');
 await page.getByRole('button',{name:'Sačuvaj posao',exact:true}).click();
 await expect(page).toHaveURL(/\/posao\/AT-[^/]+$/);
 await expect(page.locator('.job-line')).toContainText('Porta Royal CPL Bela Premium · Bela · DK');
 await expect(page.locator('.job-line')).toContainText('1800 × 2110');
});
